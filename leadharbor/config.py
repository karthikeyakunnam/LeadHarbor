from dataclasses import dataclass, field
from pathlib import Path
import json
import os

ROOT = Path(__file__).resolve().parent.parent


def load_env(path=ROOT / '.env'):
    """Read literal KEY=value settings; never evaluate shell code."""
    if path.exists():
        for line in path.read_text().splitlines():
            line = line.strip()
            if line and not line.startswith('#') and '=' in line:
                key, value = line.split('=', 1)
                os.environ.setdefault(key.strip(), value.strip())


@dataclass
class Settings:
    db_path: str = 'data/leadharbor.sqlite3'
    host: str = '127.0.0.1'
    port: int = 8080
    public_url: str = 'http://localhost:8080'
    admin_password_hash: str = ''
    admin_token: str = ''
    ingest_token: str = ''
    session_secret: str = ''
    secure_cookies: bool = False
    demo: bool = False
    worker_enabled: bool = True
    llm_base_url: str = 'https://api.openai.com/v1'
    llm_api_key: str = ''
    llm_model: str = 'gpt-4o-mini'
    llm_json_mode: bool = True
    input_price_per_million: float = 0.0
    output_price_per_million: float = 0.0
    webhook_url: str = ''
    webhook_token: str = ''
    retention_days: int = 90
    max_attempts: int = 3
    rules: dict = field(default_factory=dict)

    @classmethod
    def from_env(cls):
        load_env()
        rules_path = Path(os.getenv('SCORING_RULES_PATH', str(ROOT / 'config/scoring.json')))
        obj = cls(
            db_path=os.getenv('DATABASE_PATH', 'data/leadharbor.sqlite3'),
            host=os.getenv('HOST', '127.0.0.1'), port=int(os.getenv('PORT', '8080')),
            public_url=os.getenv('PUBLIC_URL', 'http://localhost:8080').rstrip('/'),
            admin_password_hash=os.getenv('ADMIN_PASSWORD_HASH', ''),
            admin_token=os.getenv('ADMIN_TOKEN', ''), ingest_token=os.getenv('INGEST_TOKEN', ''),
            session_secret=os.getenv('SESSION_SECRET', ''),
            secure_cookies=os.getenv('SECURE_COOKIES', 'false').lower() == 'true',
            demo=os.getenv('DEMO_MODE', 'false').lower() == 'true',
            worker_enabled=os.getenv('WORKER_ENABLED', 'true').lower() == 'true',
            llm_base_url=os.getenv('LLM_BASE_URL', 'https://api.openai.com/v1').rstrip('/'),
            llm_api_key=os.getenv('LLM_API_KEY', ''), llm_model=os.getenv('LLM_MODEL', 'gpt-4o-mini'),
            llm_json_mode=os.getenv('LLM_JSON_MODE', 'true').lower() == 'true',
            input_price_per_million=float(os.getenv('LLM_INPUT_PRICE_PER_MILLION', '0')),
            output_price_per_million=float(os.getenv('LLM_OUTPUT_PRICE_PER_MILLION', '0')),
            webhook_url=os.getenv('EVENT_WEBHOOK_URL', ''), webhook_token=os.getenv('EVENT_WEBHOOK_TOKEN', ''),
            retention_days=int(os.getenv('RETENTION_DAYS', '90')),
            max_attempts=int(os.getenv('MAX_ATTEMPTS', '3')),
            rules=json.loads(rules_path.read_text()),
        )
        obj.validate()
        return obj

    def validate(self):
        from urllib.parse import urlsplit
        if not all(len(x) >= 32 for x in (self.admin_token, self.ingest_token, self.session_secret)):
            raise ValueError('Run python3 scripts/setup.py first: authentication secrets must be at least 32 characters.')
        if not self.admin_password_hash.startswith('pbkdf2_sha256$'):
            raise ValueError('ADMIN_PASSWORD_HASH must be generated by scripts/setup.py.')
        u = urlsplit(self.public_url)
        if u.scheme not in ('http', 'https') or not u.hostname or u.path not in ('', '/'):
            raise ValueError('PUBLIC_URL must be an HTTP(S) origin without a path.')
        if u.scheme == 'https' and not self.secure_cookies:
            raise ValueError('HTTPS deployments require SECURE_COOKIES=true.')
        if u.scheme != 'https' and u.hostname not in ('localhost', '127.0.0.1', '::1'):
            raise ValueError('Non-local deployments require HTTPS.')
        if self.demo and self.host not in ('127.0.0.1', 'localhost', '::1'):
            raise ValueError('Demo mode must listen on loopback only.')
        if not 1 <= self.max_attempts <= 10 or not 1 <= self.retention_days <= 3650:
            raise ValueError('Invalid retry or retention settings.')
        for raw in (self.llm_base_url, self.webhook_url):
            if raw:
                u = urlsplit(raw)
                if u.scheme not in ('https', 'http') or not u.hostname or u.username or u.password:
                    raise ValueError('Integration endpoints must be HTTP(S) URLs without credentials.')
                if u.scheme == 'http' and u.hostname not in ('localhost', '127.0.0.1', '::1', 'n8n', 'host.docker.internal'):
                    raise ValueError('Remote integration endpoints require HTTPS.')
        if self.webhook_url and len(self.webhook_token) < 32:
            raise ValueError('Configured event webhooks require a token of at least 32 characters.')
        llm = urlsplit(self.llm_base_url)
        if llm.query or llm.fragment:
            raise ValueError('LLM_BASE_URL must not contain a query or fragment.')
        r = self.rules
        if not isinstance(r, dict):
            raise ValueError('Scoring policy must be a JSON object.')
        for key, maximum in [('about_us', 4000), ('ideal_customer', 3000), ('default_owner', 150), ('hot_owner', 150), ('privacy_contact', 300)]:
            if not isinstance(r.get(key), str) or not 1 <= len(r[key]) <= maximum:
                raise ValueError(f'Invalid scoring policy field: {key}.')
        for key in ('warm_threshold', 'hot_threshold'):
            if type(r.get(key)) is not int:
                raise ValueError('Scoring thresholds must be integers.')
        maximum = r.get('max_daily_ai_calls', 500)
        if type(maximum) is not int or not 1 <= maximum <= 10000:
            raise ValueError('max_daily_ai_calls must be an integer from 1 to 10000.')
        adjustments = r.get('keyword_adjustments', [])
        if not isinstance(adjustments, list) or len(adjustments) > 20:
            raise ValueError('At most 20 keyword adjustments are supported.')
        for rule in adjustments:
            if not isinstance(rule, dict) or not isinstance(rule.get('label'), str) or not 1 <= len(rule['label']) <= 100:
                raise ValueError('Each keyword adjustment needs a short label.')
            if type(rule.get('points')) is not int or not -5 <= rule['points'] <= 5:
                raise ValueError('Keyword adjustment points must be integers from -5 to 5.')
            words = rule.get('keywords')
            if not isinstance(words, list) or not 1 <= len(words) <= 20 or any(not isinstance(word, str) or not 1 <= len(word.strip()) <= 100 for word in words):
                raise ValueError('Each keyword adjustment needs 1–20 non-empty keywords.')
        hours = r.get('follow_up_hours', {})
        if not isinstance(hours, dict):
            raise ValueError('Follow-up hours must be an object.')
        for value in hours.values():
            if type(value) not in (int, float) or not .1 <= value <= 720:
                raise ValueError('Follow-up windows must be from 0.1 to 720 hours.')
        if not (1 <= r.get('warm_threshold', 5) < r.get('hot_threshold', 8) <= 10):
            raise ValueError('Scoring thresholds must satisfy 1 <= warm < hot <= 10.')
        if not 0 <= self.input_price_per_million <= 10000 or not 0 <= self.output_price_per_million <= 10000:
            raise ValueError('Token prices cannot be negative.')
