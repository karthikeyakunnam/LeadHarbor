const assert=require('node:assert/strict');
const fs=require('node:fs');
const vm=require('node:vm');
const w=JSON.parse(fs.readFileSync('workflow.json','utf8'));
const code=w.nodes.find(n=>n.name==='Prepare durable submission').parameters.jsCode;
const input={submittedAt:'2026-11-15T08:30:00Z','Full name':'Jane Doe','Work email':'jane@example.com','Message':'A project inquiry','Privacy acknowledgment':'I acknowledge the privacy notice and agree to processing for this inquiry.'};
const run=form=>vm.runInNewContext('(function(){'+code+'})()',{$input:{first:()=>({json:form})},require:name=>{assert.equal(name,'crypto');return require('node:crypto');}});
const a=run(input)[0].json,b=run(input)[0].json;
assert.equal(a.submission_key,b.submission_key);
assert.match(a.submission_key,/^n8n-[a-f0-9]{64}$/);
assert.equal(a.payload.email,input['Work email']);
assert.equal(a.payload.consent,true);
assert.notEqual(a.submission_key,run({...input,submittedAt:'2026-11-15T09:30:00Z'})[0].json.submission_key);
assert.throws(()=>run({...input,submittedAt:null}));
assert.throws(()=>run({...input,'Privacy acknowledgment':'No'}));
const notifications=JSON.parse(fs.readFileSync('workflows/notifications.json','utf8'));
const format=notifications.nodes.find(n=>n.name==='Format event').parameters.jsCode;
const event={event_id:'fixture-event',type:'lead.qualified',full_name:'<script>alert(1)</script>',email:'a@example.com',score:8,tier:'hot'};
const result=vm.runInNewContext('(function(){'+format+'})()',{$input:{first:()=>({json:{body:event}})}})[0].json;
assert.ok(!result.notification_text.includes('<'));
assert.equal(notifications.nodes.find(n=>n.type==='n8n-nodes-base.webhook').parameters.authentication,'headerAuth');
assert.ok(notifications.nodes.filter(n=>['n8n-nodes-base.slack','n8n-nodes-base.emailSend'].includes(n.type)).every(n=>n.disabled));
console.log('Workflow code checks passed: stable submission keys, consent, timestamps, notification escaping, authentication.');
